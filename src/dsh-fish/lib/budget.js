/**
 * budget.js —— 单轮回复的字数预算
 *
 * 2026-10-25 加。起因：如果用户想要她写长一点（也不在乎 token），原来没有任何入口
 * ——身份文档里既不许写「你话少」（见 persona.js 的 PRESCRIPTION_BANS），
 * 也没有反向的「可以长」。于是给一个**环境参数**：这一轮最多写多少字。
 *
 * 2026-11-03：默认从 0 改成 800，并且这句话不再只压长度。
 * 用户要的是「整体变长：闲聊 3–6 句，正经话题 300–800 字」。身份文档里的
 * STYLE_BRIEF 负责按话题定长短；这里补一条每轮都看得见的硬上限，
 * 免得她为了写满把一句话拆成三句。0 仍然表示完全不出现。
 *
 * 三条边界（改之前先读）：
 *   1. 它描述的是**这一轮产出的预算**，不是「她是什么样的人」。所以它不进身份文档，
 *      只出现在这一轮的递话 / 唤醒消息里，跟着那一轮结束就消失。
 *   2. 0 = **完全不出现这句话**，长短完全由她自己决定。
 *   3. 不做输出截断。截断会把句子切一半，比说长更难看；这里只给预算，信不信由她。
 *
 * 单独成一个文件（而不是塞进 persona.js）的原因：say.js 有一条守门测试，
 * 不许它 import './persona.js'（防止身份被重新塞回 user 消息里）。
 */

/**
 * @param {number} chars 这一轮的字数预算；<= 0 或非数字 → 空串
 * @returns {string} 可以直接拼进提示词的一句话，或空串
 */
export function lengthBudget(chars) {
  const n = Math.round(Number(chars) || 0)
  if (!(n > 0)) return ''
  return `这一轮按话题写：正经话题三百到八百字，闲聊三到六句；最多别超过 ${n} 字。别一句话打发，也别为了凑字数把一句话拆成三句。`
}
